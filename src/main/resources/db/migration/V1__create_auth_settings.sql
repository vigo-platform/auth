CREATE TABLE auth_settings
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    version                     BIGINT                                  NOT NULL,
    login_enabled               BOOLEAN                                 NOT NULL,
    register_enabled            BOOLEAN                                 NOT NULL,
    default_otp_channel         VARCHAR(16)                             NOT NULL,
    email_notification_enabled  BOOLEAN                                 NOT NULL,
    sms_notification_enabled    BOOLEAN                                 NOT NULL,
    in_app_notification_enabled BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_auth_settings PRIMARY KEY (id)
);